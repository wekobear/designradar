// Bundles the Vercel serverless entries into self-contained files under api/.
// Why: Vercel's file tracer does not resolve npm-workspace packages (node_modules/@aihot/*) —
// unbundled entries crash with ERR_MODULE_NOT_FOUND. Bundling pulls every workspace source into
// the output; only native modules stay external (traced and installed from the registry).
// The outputs are COMMITTED — Vercel's remote builder compiles functions from the uploaded
// sources (buildCommand outputs are ignored), so the committed api/server.mjs is exactly what
// runs. Run this before every commit that touches backend, industry, fonts or seeds:
//   node scripts/vercel-bundles.mjs
import { build } from "esbuild";
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import nodeFsModule from "node:fs";
import nodeFsPromisesModule from "node:fs/promises";
import path from "node:path";

// ---- Embedded runtime assets ---------------------------------------------------------------
// The API bundle reads static files from the repo at runtime (prompts, brand, fonts, the OpenAPI
// spec, leaderboard seeds, harfbuzzjs wasm). Function outputs only contain traced files, and
// functions.includeFiles is ignored for this project, so the assets are embedded into the bundle
// and served through fs shims (deploy/fs-shim.mjs, deploy/fs-promises-shim.mjs).
const EMBED_DIRS = ["industry", "assets/og-fonts", "reference", "database/seeds", "node_modules/harfbuzzjs"];
const root = path.resolve(import.meta.dirname, "..");

function collectFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...collectFiles(full));
    else out.push(full);
  }
  return out;
}

const embedded = {};
for (const dir of EMBED_DIRS) {
  for (const file of collectFiles(path.join(root, dir))) {
    embedded[path.relative(root, file).split(path.sep).join("/")] = readFileSync(file).toString("base64");
  }
}
mkdirSync(path.join(root, "deploy"), { recursive: true });
writeFileSync(
  path.join(root, "deploy/embedded-assets.mjs"),
  "// Generated by scripts/vercel-bundles.mjs — base64 of repo files the API bundle reads at runtime.\n" +
    `export const EMBEDDED = ${JSON.stringify(embedded)};\n`,
);

// ---- fs shims -------------------------------------------------------------------------------
// The bundle keeps real `import { readFileSync } from "node:fs"` statements for workspace code, and
// ESM named bindings snapshot at import time — mutating node:fs after the fact has no effect.
// esbuild aliases node:fs (and fs/promises) to these shims instead: they re-export the whole real
// module surface with embedded-map-aware overrides created at module init.
const shimHeader = `import { EMBEDDED } from "./embedded-assets.mjs";
// Bundled modules share one scope, so import.meta.dirname is the bundle file's directory (…/api);
// the repo root that mapped paths are keyed against is its parent.
const repoRoot = new URL("..", import.meta.url).pathname.replace(/\\/+$/, "");
const keyOf = (p) => {
  if (typeof p !== "string" && !(p instanceof URL)) return null;
  const norm = String(p).split("\\\\").join("/");
  // harfbuzzjs reads its wasm via a hard-coded __dirname; map it wherever the bundle runs.
  const hb = "/node_modules/harfbuzzjs/";
  const hbAt = norm.indexOf(hb);
  if (hbAt >= 0) return "node_modules/harfbuzzjs/" + norm.slice(hbAt + hb.length);
  if (!norm.startsWith(repoRoot + "/")) return null;
  return norm.slice(repoRoot.length + 1);
};
const embeddedBuf = (key) => Buffer.from(EMBEDDED[key], "base64");
`;

function passthrough(mod, names) {
  const valid = names.filter((n) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n));
  return valid.map((n) => `export const ${n} = real.${n};`).join("\n") + "\n";
}

const nodeFsKeys = Object.keys(nodeFsModule).filter((k) => !["readFileSync", "existsSync", "statSync", "createReadStream"].includes(k));
const nodeFspKeys = Object.keys(nodeFsPromisesModule).filter((k) => !["readFile", "stat"].includes(k));

writeFileSync(
  path.join(root, "deploy/fs-shim.mjs"),
  shimHeader +
    'import { createRequire as __shimCreateRequire } from "node:module";\n' +
    'const real = __shimCreateRequire(import.meta.url)("node:fs");\n' +
    `export const readFileSync = function (p, options) {
  const key = keyOf(p);
  if (key && key in EMBEDDED) {
    const buf = embeddedBuf(key);
    const enc = typeof options === "string" ? options : options?.encoding;
    return enc ? buf.toString(enc) : buf;
  }
  return real.readFileSync(p, options);
};
export const existsSync = function (p) {
  const key = keyOf(p);
  if (key && key in EMBEDDED) return true;
  return real.existsSync(p);
};
export const statSync = function (p, options) {
  const key = keyOf(p);
  if (key && key in EMBEDDED) {
    const size = embeddedBuf(key).length;
    return { size, isFile: () => true, isDirectory: () => false, isSymbolicLink: () => false };
  }
  return real.statSync(p, options);
};
export const createReadStream = function (p, options) {
  const key = keyOf(p);
  if (!(key && key in EMBEDDED)) return real.createReadStream(p, options);
  const { Readable } = require("node:stream");
  return Readable.from(embeddedBuf(key));
};
` + passthrough(nodeFsModule, nodeFsKeys) + "export default real;\n",
);

writeFileSync(
  path.join(root, "deploy/fs-promises-shim.mjs"),
  shimHeader +
    'import { createRequire as __shimCreateRequireP } from "node:module";\n' +
    'const real = __shimCreateRequireP(import.meta.url)("node:fs/promises");\n' +
    `export const readFile = async function (p, options) {
  const key = keyOf(p);
  if (key && key in EMBEDDED) {
    const buf = embeddedBuf(key);
    const enc = typeof options === "string" ? options : options?.encoding;
    return enc ? buf.toString(enc) : buf;
  }
  return real.readFile(p, options);
};
export const stat = async function (p, options) {
  const key = keyOf(p);
  if (key && key in EMBEDDED) {
    const size = embeddedBuf(key).length;
    return { size, isFile: () => true, isDirectory: () => false, isSymbolicLink: () => false };
  }
  return real.stat(p, options);
};
` + passthrough(nodeFsPromisesModule, nodeFspKeys) + "export default real;\n",
);
console.log(`embedded assets: ${Object.keys(embedded).length} files, ${Math.round(JSON.stringify(embedded).length / 1048576)} MB; fs shims written`);

// ---- esbuild bundles -----------------------------------------------------------------------
const native = ["sharp", "@resvg/resvg-js", "highs"];
// harfbuzzjs is bundled (not external) so its wasm read goes through the aliased fs shim; its
// Emscripten glue uses __dirname, which does not exist in ESM — point it at the traced location.
const serverDefine = { __dirname: '"/var/task/node_modules/harfbuzzjs"' };
const fsAliases = {
  "node:fs": "./deploy/fs-shim.mjs",
  fs: "./deploy/fs-shim.mjs",
  "node:fs/promises": "./deploy/fs-promises-shim.mjs",
  "fs/promises": "./deploy/fs-promises-shim.mjs",
};
// CJS dependencies (react-dom/server, avvio, …) call require() at runtime; ESM output needs one.
// esbuild injects its own createRequire import for external CJS packages, so use another name.
const banner = { js: `import { createRequire as __bannerCreateRequire } from "node:module"; const require = __bannerCreateRequire(import.meta.url);` };

await build({
  entryPoints: ["deploy/server.ts"],
  outfile: "api/server.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  sourcemap: false,
  external: native,
  alias: fsAliases,
  define: serverDefine,
  banner,
  logLevel: "warning",
});

await build({
  entryPoints: ["deploy/ssr.ts"],
  outfile: "api/ssr.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  sourcemap: false,
  banner,
  logLevel: "warning",
});

console.log("vercel bundles: api/server.mjs, api/ssr.mjs");
